/** Small, offline overview layer derived from the already bundled GeoNames data. */
const fs = require('node:fs');
const path = require('node:path');

function buildLandmarks(data) {
  const L = data.landmarks;
  const features = [];
  for (let i = 0; i < L.count; i++) {
    // Language coverage is our existing notability proxy, not the tile's
    // within-cell POI rank. Ordinary transport and medical facilities are
    // deliberately left to the detailed vector map.
    if (L.rank[i] < 20 || /hospital|medical cent(er|re)|airport|railway station|bus station|train station/i.test(L.en[i])) continue;
    features.push({ type: 'Feature', id: L.gid[i], geometry: { type: 'Point', coordinates: [L.lng[i], L.lat[i]] },
      properties: { name: L.en[i], 'name:en': L.en[i], 'name:zh-Hans': L.zh[i] || L.en[i], score: L.rank[i] } });
  }
  // The GeoNames feature-code selection used by the library's location
  // lookup omits some iconic buildings. Supplement these public geographic
  // facts without changing that dataset or the library's location lookup.
  const additions = [
    ['Empire State Building', '帝国大厦', -73.9857, 40.7484, 70],
    ['Taj Mahal', '泰姬陵', 78.0421, 27.1751, 80],
    ['Big Ben', '大本钟', -0.1246, 51.5007, 65],
  ];
  for (const [name, zh, lng, lat, score] of additions) {
    if (features.some(f => f.properties.name === name && Math.abs(f.geometry.coordinates[0] - lng) < 0.01 && Math.abs(f.geometry.coordinates[1] - lat) < 0.01)) continue;
    features.push({ type: 'Feature', id: name, geometry: { type: 'Point', coordinates: [lng, lat] },
      properties: { name, 'name:en': name, 'name:zh-Hans': zh, score } });
  }
  features.sort((a, b) => b.properties.score - a.properties.score || String(a.id).localeCompare(String(b.id)));
  return { type: 'FeatureCollection', features };
}

function writeLandmarks(dir) {
  const data = JSON.parse(fs.readFileSync(path.join(__dirname, '../resources/geo/landmarks.json'), 'utf8'));
  const collection = buildLandmarks(data);
  const output = '/** GENERATED by tools/build-map-landmarks.js. Landmark names: GeoNames, CC BY 4.0.\n'
    + ' * Source: resources/geo/landmarks.json. Geographic supplements documented in the generator. */\n'
    + 'window.__PhotosMapLandmarks = ' + JSON.stringify(collection) + ';\n';
  fs.writeFileSync(path.join(dir, 'landmarks.js'), output);
  return collection;
}

module.exports = { buildLandmarks, writeLandmarks };

#!/usr/bin/env node
/**
 * tools/audit-writes.js  (M11)
 *
 * Finds every place in src/ that can modify the file system or start another program, and
 * checks each (file, kind) against tools/audit-writes-allow.json, where a person recorded what
 * it writes and why that is safe. A site that is not listed, or a file that has more sites
 * than listed, fails the check. `--write-doc` regenerates docs/ZERO-WRITES-AUDIT.md.
 *
 *   node tools/audit-writes.js --check
 *   node tools/audit-writes.js --write-doc
 *   node tools/audit-writes.js --list         (print every site found)
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ALLOW = JSON.parse(fs.readFileSync(path.join(__dirname, 'audit-writes-allow.json'), 'utf8'));
const DOC = path.join(ROOT, 'docs', 'ZERO-WRITES-AUDIT.md');

const FS = '(?:fs|fsp|fs\\.promises)';
const KINDS = [
  { id: 'fs-mutate', re: new RegExp('\\b' + FS + '\\.(writeFile|appendFile|truncate|mkdir|mkdtemp|rename|copyFile|cp|unlink|rm|rmdir|symlink|link|utimes|lutimes|chmod|chown)(Sync)?\\(') },
  { id: 'fs-open-write', re: new RegExp('\\b' + FS + '\\.open(Sync)?\\((?![^)]*[\'"]r[\'"])') },
  { id: 'write-stream', re: /\bcreateWriteStream\(/ },
  { id: 'image-output', re: /\.toFile\(/ },
  { id: 'child-process', re: /require\(['"]child_process['"]\)/ },
  { id: 'sqlite-attach', re: /\b(ATTACH\b|VACUUM INTO)/ },
  { id: 'sqlite-open', re: /new Database\(/ },
  { id: 'electron-path', re: /\.setPath\(/ },
  { id: 'shell-action', re: /\bshell\.(trashItem|openPath|showItemInFolder|openExternal)\(/ },
  { id: 'save-dialog', re: /showSaveDialog/ },
  { id: 'download', re: /\b(downloadURL|will-download|net\.download)\b/ },
  { id: 'external-tool-name', re: /['"`](xattr|touch|SetFile|chflags|rsync|cp|mv|rm)['"`]\s*[,)]/ },
];

function walk(dir, out) {
  for (const n of fs.readdirSync(dir)) {
    const p = path.join(dir, n);
    const st = fs.statSync(p);
    if (st.isDirectory()) { if (n !== 'vendor' && n !== 'node_modules') walk(p, out); } else if (n.endsWith('.js')) out.push(p);
  }
  return out;
}

const sites = new Map(); // "file|id" -> { file, id, lines: [] }
for (const f of walk(path.join(ROOT, 'src'), [])) {
  const rel = path.relative(ROOT, f).split(path.sep).join('/');
  const lines = fs.readFileSync(f, 'utf8').split('\n');
  lines.forEach((line, i) => {
    const t = line.trim();
    if (t.startsWith('//') || t.startsWith('*') || t.startsWith('/*')) return;
    for (const k of KINDS) {
      if (!k.re.test(line)) continue;
      const key = rel + '|' + k.id;
      if (!sites.has(key)) sites.set(key, { file: rel, id: k.id, lines: [] });
      sites.get(key).lines.push(i + 1);
    }
  });
}

const problems = [];
const allowByKey = new Map((ALLOW.sites || []).map((e) => [e.file + '|' + e.id, e]));
for (const [key, s] of sites) {
  const a = allowByKey.get(key);
  if (!a) problems.push('unlisted write site: ' + s.file + ' [' + s.id + '] at line ' + s.lines.join(', '));
  else if (s.lines.length > a.max) problems.push('more sites than listed: ' + s.file + ' [' + s.id + '] has ' + s.lines.length + ', allowlist says ' + a.max);
}
for (const [key, a] of allowByKey) if (!sites.has(key)) problems.push('allowlist entry matches nothing (remove it): ' + key);

if (process.argv.includes('--list')) for (const s of sites.values()) console.log(s.file + ' [' + s.id + '] lines ' + s.lines.join(','));

if (process.argv.includes('--write-doc')) {
  const rows = [...sites.values()].sort((x, y) => (x.file + x.id).localeCompare(y.file + y.id)).map((s) => {
    const a = allowByKey.get(s.file + '|' + s.id) || {};
    return '| `' + s.file + '` | ' + s.id + ' | ' + s.lines.length + ' | ' + (a.writes || '?') + ' | ' + (a.safe || '?') + ' |';
  });
  const text = '# Zero writes to source folders: audit\n\n'
    + 'Promise: Photos never writes, moves, renames, deletes or labels any file in a source folder, and never creates a file beside one. '
    + 'User edits (favourites, titles, captions, keywords, rotation, people corrections) live only in the app database.\n\n'
    + '_Generated by `node tools/audit-writes.js --write-doc`; the CI job `node tools/audit-writes.js --check` fails when a new write site appears that is not explained in `tools/audit-writes-allow.json`._\n\n'
    + '## Layers of protection\n\n'
    + '1. **Static audit** (this table): every call that can change the file system or run a program, with where it writes and why that is safe.\n'
    + '2. **Runtime write guard** (`src/main/write-guard.js`, loaded first in the main process and in every worker thread): wraps Node’s `fs` and `fs/promises` mutating functions and `createWriteStream`. A target that resolves (symbolic links followed, `..` removed, case-folded, Unicode-normalised) inside any registered source folder, or outside the data folder and the temp folders, is refused with an error and a log line. The source list follows the database at once when a folder is added, removed or relinked.\n'
    + '3. **External-tool validation** (`src/main/safe-exec.js`): the only way a program is started. Only `sips`, `ffmpeg`, `ffprobe`, `stat`, `mount` and `plutil` are allowed; every output path must pass the write guard; `sips` must always have `--out`; `ffmpeg` needs `-nostdin`, one input, one output.\n'
    + '4. **Safe deletion** (`src/main/storage/safe-delete.js`): only the contents of a known cache folder inside the data folder can be cleared; symbolic links are removed, never followed.\n'
    + '5. **Read-only disk image test and before/after fingerprint** in CI (`tools/ci-smoke.sh`, `tools/verify-readonly.js`).\n\n'
    + '## Write sites in `src/`\n\n| File | Kind | Sites | What it writes (path it resolves to) | Why it is safe |\n|---|---|---|---|---|\n' + rows.join('\n') + '\n\n'
    + '## Not visible to the write guard\n\n' + (ALLOW.notes || []).map((n) => '- ' + n).join('\n') + '\n';
  fs.mkdirSync(path.dirname(DOC), { recursive: true });
  fs.writeFileSync(DOC, text);
  console.log('wrote docs/ZERO-WRITES-AUDIT.md');
}

if (process.argv.includes('--check') || !process.argv.slice(2).length) {
  if (problems.length) { console.error(problems.length + ' audit problem(s):'); problems.forEach((p) => console.error('  ' + p)); process.exit(1); }
  console.log('write audit OK: ' + sites.size + ' site groups, all explained in tools/audit-writes-allow.json.');
}
